// Regenerates src/lib/famousRaces.ts from docs/race-gpx-manifest/races.json.
// Run with: npm run gen:races
import fs from 'node:fs'

const REPO = new URL('..', import.meta.url).pathname
const SRC = `${REPO}docs/race-gpx-manifest/races.json`
const OUT = `${REPO}src/lib/famousRaces.ts`

const GROUP_LABELS = {
  '1_short_20k': '20K / Sky / VK',
  '2_50k': '50K',
  '3_100k': '100K',
  '4_100m_multistage': '100M / Multi-stage',
}

function slugify(name, row) {
  const base = name
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')
  return `${base}-${row}`
}

const data = JSON.parse(fs.readFileSync(SRC, 'utf8'))
const out = []

out.push('// Generated by scripts/gen-famous-races.mjs from docs/race-gpx-manifest/races.json.')
out.push('// Do not hand-edit — change the manifest and run `npm run gen:races`.')
out.push('')
out.push('export interface FamousRace {')
out.push('  id: string')
out.push('  row: number')
out.push('  name: string')
out.push('  organizer: string')
out.push('  location: string')
out.push('  continent: string')
out.push('  distance: string')
out.push('  officialDPlus: string')
out.push('  category: string')
out.push('  dateLabel: string')
out.push('  gpxSource: string')
out.push('  login: string')
out.push('  terms: string')
out.push('  groupLabel: string')
out.push('}')
out.push('')
out.push('export const FAMOUS_RACES: FamousRace[] = [')

for (const [key, rows] of Object.entries(data.categories)) {
  for (const r of rows) {
    out.push('  {')
    out.push(`    id: ${JSON.stringify(slugify(r.name, r.row))},`)
    out.push(`    row: ${r.row},`)
    out.push(`    name: ${JSON.stringify(r.name)},`)
    out.push(`    organizer: ${JSON.stringify(r.organizer)},`)
    out.push(`    location: ${JSON.stringify(r.location)},`)
    out.push(`    continent: ${JSON.stringify(r.continent)},`)
    out.push(`    distance: ${JSON.stringify(r.distance)},`)
    out.push(`    officialDPlus: ${JSON.stringify(r.officialDPlus)},`)
    out.push(`    category: ${JSON.stringify(r.category)},`)
    out.push(`    dateLabel: ${JSON.stringify(r.date)},`)
    out.push(`    gpxSource: ${JSON.stringify(r.gpxSource)},`)
    out.push(`    login: ${JSON.stringify(r.login)},`)
    out.push(`    terms: ${JSON.stringify(r.terms)},`)
    out.push(`    groupLabel: ${JSON.stringify(GROUP_LABELS[key])},`)
    out.push('  },')
  }
}

out.push(']')
out.push('')
out.push('export const FAMOUS_RACE_GROUPS = [')
for (const label of Object.values(GROUP_LABELS)) out.push(`  ${JSON.stringify(label)},`)
out.push('] as const')
out.push('')

fs.writeFileSync(OUT, out.join('\n'))
const total = Object.values(data.categories).reduce((n, rows) => n + rows.length, 0)
console.log(`wrote ${OUT} (${total} races)`)
